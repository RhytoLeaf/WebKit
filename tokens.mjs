/* tokens.mjs — design-token pipeline: tokens.json -> dist/tokens.css (CSS custom properties).
   Run: node tokens.mjs   (CI verifies the committed dist/tokens.css matches, so tokens are the single source of truth) */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const tokens = JSON.parse(readFileSync(new URL('./tokens.json', import.meta.url), 'utf8'));
const lines = ['/* Generated by tokens.mjs from tokens.json — do not edit by hand. */', ':root {'];

function walk(obj, prefix) {
  for (const [key, value] of Object.entries(obj)) {
    const name = `--wk-${prefix ? prefix + '-' : ''}${key}`;
    if (value !== null && typeof value === 'object') {
      walk(value, name.replace(/^--wk-/, ''));
    } else {
      lines.push(`  ${name}: ${value};`);
    }
  }
}

walk(tokens, '');
lines.push('}');

mkdirSync(new URL('./dist', import.meta.url), { recursive: true });
writeFileSync(new URL('./dist/tokens.css', import.meta.url), lines.join('\n') + '\n');
console.log(`wrote dist/tokens.css (${lines.length - 2} tokens)`);
